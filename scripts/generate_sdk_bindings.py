"""Regenerate direct, compile-checked calls from the frozen SDK surface. Build needs no Python."""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
surface = json.loads((root / 'src/Studio5000.Core/SdkSurface.json').read_text(encoding='utf-8-sig'))
methods = {m['name']: m for m in surface['methods']}
managed = {'AddEventHandler', 'RemoveEventHandler', 'ClearEventHandlers', 'Dispose'}
factories = {'OpenLogixProjectAsync', 'CreateNewProjectAsync', 'ConvertAsync', 'UploadToNewProjectAsync'}
types = {'System.String':'string', 'System.Boolean':'bool', 'System.SByte':'sbyte', 'System.Byte':'byte',
         'System.Int16':'short', 'System.UInt16':'ushort', 'System.Int32':'int', 'System.UInt32':'uint',
         'System.Int64':'long', 'System.UInt64':'ulong', 'System.Single':'float', 'System.Double':'double', 'System.Byte[]':'byte[]'}

def value(p):
    t, n = p['type'], p['name']
    if t == 'System.Threading.CancellationToken': return 'ct'
    if 'IOperationEvent' in t: return 'logger'
    typ = 'LogixProject.' + t.split('+')[1] if '+' in t else types[t]
    default = ''
    if p['optional']:
        d = p['defaultValue']
        if t == 'System.String': d = json.dumps(d or '')
        elif t == 'System.Boolean': d = d.lower()
        elif '+' in t: d = typ + '.' + d
        default = ', ' + d
    return f'Arg<{typ}>(args, "{n}"{default})'

lines = ['// Generated by scripts/generate_sdk_bindings.py; every SDK invocation is compiled against 2.1.974.', '#nullable enable',
         'using System.Text.Json;', 'using RockwellAutomation.LogixDesigner;', 'using RockwellAutomation.LogixDesigner.Logging;',
         '', 'namespace Studio5000.NativeBridge;', '', 'internal static partial class SdkRunner', '{',
         '    private static async Task<LogixProject> CreateAsync(string method, Dictionary<string, JsonElement> args, IOperationEvent logger, CancellationToken ct)',
         '    {', '        return method switch', '        {']
for name in sorted(factories):
    m = next(m for m in surface['methods'] if m['name'] == name) # single logger overload
    lines.append(f'            "{name}" => await LogixProject.{name}(' + ', '.join(value(p) for p in m['parameters']) + '),')
lines += ['            _ => throw new ArgumentException("Unknown project factory.")', '        };', '    }',
          '    private static async Task<object?> InvokeAsync(LogixProject? project, string method, Dictionary<string, JsonElement> args, CancellationToken ct)',
          '    {', '        switch (method)', '        {']
for name in sorted(methods.keys() - managed - factories):
    m = methods[name]
    call = ('LogixProject.' if m['isStatic'] else 'project!.') + name + '(' + ', '.join(value(p) for p in m['parameters']) + ')'
    lines.append(f'            case "{name}":')
    if '`1' in m['returns']: lines.append('                return await ' + call + ';')
    else: lines.append('                await ' + call + '; return null;')
lines += ['            default: throw new ArgumentException("Method is not bound to the SDK.");', '        }', '    }', '}', '']
(root / 'src/Studio5000.NativeBridge/SdkBindings.g.cs').write_text('\n'.join(lines), encoding='utf-8')
